    /// <summary>
    /// This method reports whether a metal is known by the given name.
    /// </summary>
    /// <param name="name">The metal's name.</param>
    /// <returns><c>true</c>, if it is known, or <c>false</c>, if not.</returns>
    public static bool IsKnown(string name)
    {
        return name is not null && Tables.ContainsKey(name);
    }

    /// <summary>
    /// This method returns a metal's complex index of refraction at the given wavelength, each part read
    /// between its measurements in a straight line, and held at its first or last beyond them.
    /// </summary>
    /// <param name="name">The metal's name.</param>
    /// <param name="wavelength">The wavelength, in nanometers.</param>
    /// <returns>The complex index there: how far it bends light, and how fast it swallows it.</returns>
    public static Complex IndexAt(string name, double wavelength)
    {
        double[] table = Tables[name];
        int last = table.Length - 3;

        if (wavelength <= table[0])
            return new Complex(table[1], table[2]);

        if (wavelength >= table[last])
            return new Complex(table[last + 1], table[last + 2]);

        int index = 0;

        while (table[index + 3] < wavelength)
            index += 3;

        double fraction = (wavelength - table[index]) / (table[index + 3] - table[index]);

        return new Complex(
            table[index + 1] + fraction * (table[index + 4] - table[index + 1]),
            table[index + 2] + fraction * (table[index + 5] - table[index + 2]));
    }
